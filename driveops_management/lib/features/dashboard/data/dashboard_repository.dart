class DashboardRepository {
  List<Driver> getDrivers() {
    return _dummyDrivers;
  }

  List<Driver> getActiveDrivers() {
    return _dummyDrivers.where((d) => d.status == DriverStatus.active).toList();
  }

  List<Vehicle> getVehicles() {
    return _dummyVehicles;
  }

  List<Vehicle> getVehiclesNeedingService() {
    final now = DateTime.now();
    final thirtyDaysFromNow = now.add(const Duration(days: 30));

    return _dummyVehicles.where((v) {
      if (v.status == VehicleStatus.maintenance) return true;
      if (v.insuranceExpiryDate.isBefore(thirtyDaysFromNow)) return true;
      if (v.registrationExpiryDate.isBefore(thirtyDaysFromNow)) return true;
      return false;
    }).toList();
  }

  List<Trip> getRecentTrips() {
    return _dummyTrips;
  }

  Map<String, int> getTripStatistics() {
    final completed = _dummyTrips.where((t) => t.tripStatus == TripStatus.completed).length;
    final cancelled = _dummyTrips.where((t) => t.tripStatus == TripStatus.cancelled).length;
    final noDriver = _dummyTrips.where((t) => t.tripStatus == TripStatus.noDriverAvailable).length;

    return {
      'completed': completed,
      'cancelled': cancelled,
      'noDriverAvailable': noDriver,
    };
  }

  double getTotalRevenue() {
    return _dummyDrivers.fold(0.0, (sum, d) => sum + d.totalRevenue);
  }

  List<Driver> getDriverScoreboard() {
    final sorted = List<Driver>.from(_dummyDrivers)
      ..sort((a, b) {
        final ratingCompare = b.rating.compareTo(a.rating);
        if (ratingCompare != 0) return ratingCompare;
        return b.totalTrips.compareTo(a.totalTrips);
      });
    return sorted.take(5).toList();
  }

